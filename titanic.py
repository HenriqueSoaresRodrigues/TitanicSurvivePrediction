import shap
import lime
import lime.lime_tabular
import matplotlib.pyplot as plt
import numpy as np
from sklearn.impute import SimpleImputer

# 1. Preparação dos dados pós-pipeline para o SHAP
preprocessor = pipeline.named_steps['preprocessor']
classifier = pipeline.named_steps['classifier']

X_train_transformed = preprocessor.transform(X_train)
X_test_transformed = preprocessor.transform(X_test)

# Nomes das features após o ColumnTransformer
feature_names = numerical_columns + categorical_columns_for_transformer

# Como o LIME e o SHAP não lidam bem com NaNs na amostragem interna,
# vamos imputar os NaNs nos arrays transformados apenas para a análise de explicabilidade.
imputer = SimpleImputer(strategy='median')
X_train_clean = imputer.fit_transform(X_train_transformed)
X_test_clean = imputer.transform(X_test_transformed)

# --- ANÁLISE COM SHAP ---
print("--- Executando análise com SHAP ---")
# Usando o TreeExplainer para o HistGradientBoostingClassifier
explainer_shap = shap.TreeExplainer(classifier)
shap_values = explainer_shap(X_test_clean)

# Gráfico de resumo (Summary Plot) global
plt.figure(figsize=(10, 6))
shap.summary_plot(shap_values, X_test_clean, feature_names=feature_names, show=False)
plt.title("SHAP Summary Plot (Global)", fontsize=14)
plt.tight_layout()
plt.show()

# Gráfico de força (Waterfall Plot) para a primeira instância do teste
plt.figure(figsize=(10, 4))
shap.plots.waterfall(shap_values[0], show=False)
plt.title("SHAP Waterfall Plot (Local - Primeira Instância)", fontsize=14)
plt.tight_layout()
plt.show()

# --- ANÁLISE COM LIME ---
print("\n--- Executando análise com LIME ---")
# Criando o explicador tabular do LIME usando os dados limpos (sem NaNs)
explainer_lime = lime.lime_tabular.LimeTabularExplainer(
    training_data=np.array(X_train_clean),
    feature_names=feature_names,
    class_names=['Faleceu', 'Sobreviveu'],
    mode='classification'
)

# Explicando a primeira instância do conjunto de testes
exp = explainer_lime.explain_instance(
    data_row=X_test_clean[0],
    predict_fn=classifier.predict_proba,
    num_features=len(feature_names)
)

# Mostrando a visualização local do LIME no notebook
fig = exp.as_pyplot_figure()
plt.title("Explicação LIME (Local - Primeira Instância)", fontsize=14)
plt.tight_layout()
plt.show()

"""### Explicação dos Resultados (SHAP e LIME)

#### 1. SHAP (SHapley Additive exPlanations)
O SHAP nos ajuda a entender o comportamento global do modelo e a tomada de decisão para indivíduos específicos:

* **SHAP Summary Plot (Global):**
  * Este gráfico resume as variáveis mais importantes do modelo de cima para baixo. No caso do Titanic, **Sex** (Gênero) costuma ter o maior impacto. Valores associados ao sexo feminino aumentam as chances de sobrevivência (pontos azuis/vermelhos empurrando a previsão para valores positivos), enquanto o sexo masculino reduz essa probabilidade.
  * **Pclass** (Classe social) também tem forte influência. Classes mais baixas (como a 3ª classe) reduzem significativamente a chance de sobrevivência de um indivíduo.
  
* **SHAP Waterfall Plot (Local):**
  * Explica como o modelo tomou a decisão para a primeira pessoa do conjunto de teste.
  * Começamos a partir do valor base (a média histórica de sobrevivência $E[f(X)]$) e vemos como cada característica (idade, classe, tarifa) contribuiu com forças positivas (geralmente em vermelho/rosa) ou negativas (em azul) para chegar ao valor de previsão final do modelo.

---

#### 2. LIME (Local Interpretable Model-agnostic Explanations)
Enquanto o SHAP tem uma visão global-local integrada, o LIME foca estritamente em aproximar o comportamento do modelo de forma linear e compreensível ao redor de **uma única previsão individual** (nesse caso, o primeiro passageiro do teste):

* **Gráfico LIME (Local):**
  * A barra esquerda exibe a probabilidade atribuída pelo modelo para a classe (`Faleceu` vs. `Sobreviveu`).
  * O gráfico central mostra quais regras e valores de atributos do passageiro mais apoiaram a decisão do modelo ou foram contra ela.
  * Por exemplo, se o passageiro em análise for do sexo masculino (`Sex > 0.5`), isso aparece como uma forte barra de influência contra a sobrevivência dele, justificando a decisão local do classificador.
"""